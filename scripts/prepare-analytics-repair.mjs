/**
 * Produce a forward-only Analytics RPC repair from the reviewed final SQL.
 * Does not connect to a database. The target migration MUST first be created
 * by the Supabase CLI and must still be empty. Never modify applied migrations.
 */
import { readFileSync, writeFileSync, lstatSync } from 'node:fs';
import { resolve, dirname, basename, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../', import.meta.url));

export function buildAnalyticsRepairSql(source) {
  const required = [
    /create schema if not exists private;/i,
    /create or replace function private\.get_workspace_analytics_internal\(\)/i,
    /security definer\s+set search_path = ''/i,
    /from public\.profiles\s+where user_id = requester/i,
    /data\s*->>\s*'organization'/i,
    /data\s*->>\s*'full_name'/i,
    /revoke all on function private\.get_workspace_analytics_internal\(\) from public, anon;/i,
    /grant execute on function private\.get_workspace_analytics_internal\(\) to authenticated;/i,
    /create or replace function public\.get_workspace_analytics\(\)/i,
    /security invoker\s+set search_path = ''/i,
    /revoke all on function public\.get_workspace_analytics\(\) from public, anon;/i,
    /grant execute on function public\.get_workspace_analytics\(\) to authenticated;/i,
  ];
  if (typeof source !== 'string' || required.some(pattern => !pattern.test(source))) {
    throw new Error('Analytics source no longer satisfies the reviewed security contract.');
  }
  if (/\b(?:delete\s+from|truncate\s+table|drop\s+(?:table|schema))\b/i.test(source)) {
    throw new Error('Analytics source unexpectedly contains destructive data/schema statements.');
  }
  const normalized = source.trim();
  return [
    '-- Forward-only corrective migration. Generated from the reviewed Analytics RPC boundary.',
    '-- This is not evidence that the production schema has been inspected or repaired.',
    '-- Apply only after staging review, verified target project, and migration history comparison.',
    'begin;',
    normalized,
    'commit;',
    '',
  ].join('\n');
}

export function verifyEmptyCliMigration(filePath, root = ROOT) {
  if (!filePath || typeof filePath !== 'string') throw new Error('CLI-created migration file path required.');
  const absolute = resolve(root, filePath);
  if (dirname(absolute) !== resolve(root, 'supabase/migrations') ||
      !/^\d{14}_fix_analytics_profile_schema\.sql$/.test(basename(absolute))) {
    throw new Error('Target must be a CLI-created fix_analytics_profile_schema.sql file in supabase/migrations.');
  }
  const stats = lstatSync(absolute);
  if (!stats.isFile() || stats.isSymbolicLink()) throw new Error('Target must be a regular, non-symlink file.');
  if (stats.size !== 0 || readFileSync(absolute, 'utf8').trim()) {
    throw new Error('Refusing to overwrite a non-empty or previously applied migration file.');
  }
  return absolute;
}

export function writeCliMigration(filePath, source, root = ROOT) {
  const absolute = verifyEmptyCliMigration(filePath, root);
  const sql = buildAnalyticsRepairSql(source);
  // The source file was generated by the CLI and checked empty. This is a
  // local file write only: no database connection or deployment occurs.
  writeFileSync(absolute, sql, { flag: 'r+' });
  return absolute;
}

const runningAsScript = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (runningAsScript) {
  const sourcePath = join(ROOT, 'supabase/migrations/20260817090600_analytics_rpc_boundary.sql');
  const args = process.argv.slice(2);
  const source = readFileSync(sourcePath, 'utf8');
  if (args.length === 1 && args[0] === '--check') {
    const sql = buildAnalyticsRepairSql(source);
    console.log('Analytics repair template validated. SQL bytes: ' + Buffer.byteLength(sql, 'utf8'));
    console.log('No migration file or database has been changed.');
  } else if (args.length === 2 && args[0] === '--write') {
    const target = writeCliMigration(args[1], source);
    console.log('Wrote local corrective SQL to ' + target);
    console.log('NOT deployed: review diff, migration history, and test in staging first.');
  } else {
    console.error('Usage: node scripts/prepare-analytics-repair.mjs --check');
    console.error('   or: node scripts/prepare-analytics-repair.mjs --write supabase/migrations/<CLI-created-file>.sql');
    process.exitCode = 2;
  }
}
